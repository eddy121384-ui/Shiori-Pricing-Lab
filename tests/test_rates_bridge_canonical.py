def test_fingerprint_bytes_is_lowercase_sha256_of_the_given_bytes():
    payload = dumps_bytes({"b": 1, "a": "é"})
    assert fingerprint_bytes(payload) == hashlib.sha256(payload).hexdigest()
    assert fingerprint_bytes(bytearray(payload)) == hashlib.sha256(payload).hexdigest()
    assert fingerprint_bytes(payload) == fingerprint_bytes(payload)
    assert len(fingerprint_bytes(payload)) == SHA256_HEX_LENGTH == 64
    assert fingerprint_bytes(payload) == fingerprint_bytes(payload).lower()


@pytest.mark.parametrize("value", ["a string", None, 1, 1.5, ["bytes"]])
def test_fingerprint_bytes_rejects_non_bytes(value):
    with pytest.raises(TypeError):
        fingerprint_bytes(value)


def test_fingerprint_value_is_stable_across_key_insertion_order():
    first = {"b": 2, "a": {"y": [1, 2], "x": None}}
    second = {"a": {"x": None, "y": [1, 2]}, "b": 2}

    assert fingerprint_value(first) == fingerprint_value(second)
    assert fingerprint_value(first) == fingerprint_bytes(dumps_bytes(first))
    assert fingerprint_value(first) != fingerprint_value(
        {"b": 2, "a": {"y": [1, 3], "x": None}}
    )


def test_fingerprint_dispatches_between_serialized_payloads_and_values():
    document = {"a": [1, 2]}
    canonical_text = dumps(document)

    assert fingerprint(document) == fingerprint_value(document)
    assert fingerprint(canonical_text) == fingerprint_value(document)
    assert fingerprint(canonical_text.encode("utf-8")) == fingerprint_value(document)
    assert fingerprint(bytearray(canonical_text.encode("utf-8"))) == fingerprint_value(
        document
    )
    # A JSON *string value* is not the same payload as its canonical text.
    assert fingerprint_value("abc") != fingerprint("abc")


def test_is_valid_fingerprint_accepts_only_lowercase_sha256_hex():
    assert is_valid_fingerprint(fingerprint_value({"a": 1}))
    assert is_valid_fingerprint("0" * SHA256_HEX_LENGTH)
    assert is_valid_fingerprint("abcdef0123456789" * 4)

    assert not is_valid_fingerprint("A" * SHA256_HEX_LENGTH)
    assert not is_valid_fingerprint("a" * (SHA256_HEX_LENGTH - 1))
    assert not is_valid_fingerprint("a" * (SHA256_HEX_LENGTH + 1))
    assert not is_valid_fingerprint("g" * SHA256_HEX_LENGTH)
    assert not is_valid_fingerprint("")
    assert not is_valid_fingerprint(None)
    assert not is_valid_fingerprint(b"a" * SHA256_HEX_LENGTH)


