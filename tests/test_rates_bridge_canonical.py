def test_rates_engine_error_carries_code_message_and_detail():
    error = RatesEngineError(
        code="INVALID_KERNEL_INPUT",
        message="missing schema_version",
        detail={"field": "schema_version"},
    )

    assert error.code == "INVALID_KERNEL_INPUT"
    assert error.message == "missing schema_version"
    assert error.detail == {"field": "schema_version"}
    assert "INVALID_KERNEL_INPUT" in str(error)
    assert error.to_dict() == {
        "code": "INVALID_KERNEL_INPUT",
        "message": "missing schema_version",
        "detail": {"field": "schema_version"},
    }


def test_find_engine_cli_honours_an_existing_env_override(tmp_path, monkeypatch):
    discovered = tmp_path / "shiori_rates_cli"
    discovered.write_text("", encoding="utf-8")
    monkeypatch.setenv("SHIORI_RATES_ENGINE_CLI", str(discovered))

    assert find_engine_cli() == discovered


def test_find_engine_cli_never_fabricates_a_path(monkeypatch):
    monkeypatch.delenv("SHIORI_RATES_ENGINE_CLI", raising=False)

    resolved = find_engine_cli()

    assert resolved is None or (
        resolved.is_file() and resolved.name.startswith("shiori_rates_cli")
    )


def test_invoke_and_engine_identity_report_a_missing_cli(tmp_path):
    absent = tmp_path / "no_such_shiori_rates_cli"

    with pytest.raises(RatesEngineError) as invoke_error:
        invoke({"schema_version": "RATES_KERNEL_INPUT_V1"}, cli_path=absent)
    assert invoke_error.value.code == "ENGINE_CLI_NOT_FOUND"
    assert invoke_error.value.detail["operation"] == "validate-kernel-input"

    with pytest.raises(RatesEngineError) as identity_error:
        engine_identity(cli_path=absent)
    assert identity_error.value.code == "ENGINE_CLI_NOT_FOUND"
    assert identity_error.value.detail["operation"] == "engine-identity"


# --------------------------------------------------------------------------------------
# Python <-> C++ canonical parity fixtures.
#
# The fixture file is tracked and generated by
# ``cpp/rates_engine/tests/fixtures/generate_parity_fixtures.py`` (Python side, whose number form
# was verified against V8's ``String(number)``). Both languages assert against it, so a divergence
# between the two canonicalizers turns into a failing test on both sides rather than a silent
# fingerprint mismatch in production.
# --------------------------------------------------------------------------------------


@pytest.mark.skipif(
    not _CANONICAL_PARITY_FIXTURES.is_file(),
    reason=(
        "canonical parity fixtures are missing: "
        "cpp/rates_engine/tests/fixtures/canonical_parity_fixtures.json"
    ),
)
def test_python_matches_cpp_canonical_parity_fixtures():
    fixtures = json.loads(_CANONICAL_PARITY_FIXTURES.read_text(encoding="utf-8"))
    numbers = fixtures["numbers"]
    documents = fixtures["documents"]
    assert numbers or documents, "the parity fixture file carries no expectations"

    for entry in numbers:
        labeled = json.dumps(entry, sort_keys=True)
        assert canonical_number(float(entry["value"])) == entry["canonical"], labeled

    for entry in documents:
        assert dumps(entry["json"]) == entry["canonical"], entry["name"]
        assert fingerprint_value(entry["json"]) == entry["fingerprint"], entry["name"]
        assert is_valid_fingerprint(entry["fingerprint"]), entry["name"]
