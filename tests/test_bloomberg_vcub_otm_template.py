def test_the_canonical_synthetic_screen_parses_with_no_blocking_errors() -> None:
    parsed = read(screenshot_tokens())

    assert parsed.blocking_errors == ()
    assert parsed.table is not None
    assert parsed.table.strike_labels == STRIKE_LABELS
    assert parsed.table.row_labels == tuple(
        f"{term} x {tenor}" for term, tenor in ROW_LABELS
    )


def test_every_value_lands_on_its_own_row_and_strike_coordinate() -> None:
    table = read(screenshot_tokens()).table
    assert table is not None

    for row_index, (term, tenor) in enumerate(ROW_LABELS):
        for column_index, strike in enumerate(STRIKE_LABELS):
            assert table.value_at(term, tenor, strike) == pytest.approx(
                _synthetic_value(row_index, column_index)
            ), f"{term} x {tenor} at {strike}"


def test_the_first_and_last_coordinates_are_exact() -> None:
    """The corners are checked by name, not only by the sweep above."""

    table = read(screenshot_tokens()).table
    assert table is not None

    first_term, first_tenor = ROW_LABELS[0]
    last_term, last_tenor = ROW_LABELS[-1]
    assert (first_term, first_tenor) == ("1Mo", "1Yr")
    assert (last_term, last_tenor) == ("30Yr", "30Yr")
    assert table.value_at(first_term, first_tenor, "-200bps") == pytest.approx(
        _synthetic_value(0, 0)
    )
    assert table.value_at(first_term, first_tenor, "ATM") == pytest.approx(
        _synthetic_value(0, 4)
    )
    assert table.value_at(last_term, last_tenor, "200bps") == pytest.approx(
        _synthetic_value(len(ROW_LABELS) - 1, len(STRIKE_LABELS) - 1)
    )


