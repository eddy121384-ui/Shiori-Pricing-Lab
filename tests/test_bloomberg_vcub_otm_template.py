"""Structural tests for the VCUB OTM Swaptions / SABR template parser and
its multi-image merge (Issue #185).

Every fixture here is **synthetic**: the row labels are ordinary tenor
buckets, the strike headers are the ones the screen's own contract names,
and the numbers are generated by :func:`_synthetic_value` from row/column
indices. Nothing in this file is a Bloomberg screen capture, a Bloomberg
screen layout measurement, or a live market quote -- this repository is
public, so the real screenshots stay operator-local and are supplied by
path at live acceptance.

The token layer is where these tests bite, because that is the parser's own
contract: a reader hands it text with boxes, and everything Issue #185 cares
about -- coordinate exactness, fail-closed behaviour, and what happens when
two overlapping screenshots disagree -- is decided from those boxes alone.
"""

