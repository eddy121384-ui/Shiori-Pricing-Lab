#: The strike axis the observed screen draws, left to right.
STRIKE_LABELS = (
    "-200bps",
    "-100bps",
    "-50bps",
    "-25bps",
    "ATM",
    "25bps",
    "50bps",
    "100bps",
    "200bps",
)

#: The screen's own complete row set: the 91 ``Term x Tenor`` coordinates
#: the parser is required to reconstruct before a capture may be confirmed.
#: Taken from the production constant rather than restated, so a fixture can
#: never quietly disagree with the template the check reads.
ROW_LABELS = EXPECTED_ROWS

_HEADER_Y = 110.0
_FIRST_ROW_Y = 140.0
_ROW_PITCH = 24.0
_FIRST_COLUMN_RIGHT = 240.0
_COLUMN_PITCH = 76.0
_ANCHOR_LEFT = 40.0
_GLYPH_HEIGHT = 12.0
_CHARACTER_WIDTH = 8.0
_WORD_GAP = 4.0


def _synthetic_value(row_index: int, column_index: int) -> float:
    """A made-up, strictly distinct number per intersection -- never a quote.

    Deliberately signed: on the observed screen every column but ATM holds a
    spread, and several of them are negative, so the fixture must not prove
    the mapping only for positive numbers.
    """

    return round(-4.0 + row_index * 2.5 + column_index * 0.25, 2)


def _token(
    text: str,
    *,
    right: float,
    y_center: float,
    left: float | None = None,
) -> VCUBTextToken:
    width = len(text) * _CHARACTER_WIDTH if left is None else right - left
    return VCUBTextToken(
        text=text,
        left=right - width,
        top=y_center - _GLYPH_HEIGHT / 2.0,
        width=width,
        height=_GLYPH_HEIGHT,
        confidence=0.99,
    )


def _left_aligned(text: str, *, left: float, y_center: float) -> VCUBTextToken:
    return _token(text, right=left + len(text) * _CHARACTER_WIDTH, y_center=y_center)


def _row_y(row_index: int) -> float:
    return _FIRST_ROW_Y + row_index * _ROW_PITCH


def _column_right(column_index: int) -> float:
    return _FIRST_COLUMN_RIGHT + column_index * _COLUMN_PITCH


def _word_row(words: Sequence[str], y: float, left: float = 40.0) -> list[VCUBTextToken]:
    """One header line laid out with realistic intra-phrase spacing."""

    tokens: list[VCUBTextToken] = []
    cursor = left
    for word in words:
        tokens.append(_left_aligned(word, left=cursor, y_center=y))
        cursor += len(word) * _CHARACTER_WIDTH + _WORD_GAP
    return tokens


#: How far apart two *widgets* sit on a Bloomberg header line, against the
#: word gap inside one. Both are read off the boxes by the shared widget
#: rule, so a fixture that spaced its selectors like words would prove the
#: metadata rules against a screen Bloomberg never draws.
_WIDGET_GAP = 40.0


def _widget_row(
    widgets: Sequence[Sequence[str]], y: float, left: float = 40.0
) -> list[VCUBTextToken]:
    """One header line of separate selectors, each of several words."""

    tokens: list[VCUBTextToken] = []
    cursor = left
    for widget in widgets:
        tokens.extend(_word_row(widget, y, left=cursor))
        width = sum(len(word) * _CHARACTER_WIDTH for word in widget)
        cursor += width + _WORD_GAP * (len(widget) - 1) + _WIDGET_GAP
    return tokens


def chrome_tokens(
    *,
    vol_type: Sequence[str] = ("Normal", "Vol", "Skew▾"),
    source: str = "BVOL▾",
    display_mode: str = "Spread▾",
) -> list[VCUBTextToken]:
    """The header context above the matrix.

    The tab strip, then the three selectors this screen shows: a labelled
    ``Type``, a labelled ``Source``, and the display-mode dropdown that
    carries no label of its own.
    """

    return (
        _word_row(("11)", "Configuration", "13)", "ATM", "Swaptions", "14)", "OTM",
                   "Swaptions", "/", "SABR"), 20.0)
        + _widget_row(
            (("Type",), vol_type, ("Source",), (source,), (display_mode,)), 50.0
        )
        + _widget_row(((("Table",), ("Charts",))), 80.0)
    )


def chrome_tokens_with_selector_row(widgets: Sequence[Sequence[str]]) -> list[VCUBTextToken]:
    """The tab strip plus a hand-built selector widget row.

    For constructing Source/display-mode edge cases :func:`chrome_tokens`
    cannot represent on its own -- a missing contributor widget, or a row
    cropped right after it -- by passing exactly the widgets that line
    should carry (Codex review, PR #186).
    """

    return _word_row(
        ("11)", "Configuration", "13)", "ATM", "Swaptions", "14)", "OTM",
         "Swaptions", "/", "SABR"), 20.0
    ) + _widget_row(widgets, 50.0)


def matrix_tokens(
    *,
    rows: Sequence[int] | None = None,
    omit_cells: frozenset[tuple[int, int]] = frozenset(),
    omit_row_labels: frozenset[int] = frozenset(),
    value_overrides: dict[tuple[int, int], str] | None = None,
    strike_labels: Sequence[str] = STRIKE_LABELS,
) -> list[VCUBTextToken]:
    """The matrix itself: the corner anchor, both axes, and every cell.

    ``rows`` selects which of :data:`ROW_LABELS` this screenshot shows,
    which is how one long table is sliced into overlapping images. The rows
    keep their own y positions so a slice looks exactly like the part of the
    screen it came from.
    """

    value_overrides = value_overrides or {}
    row_indices = list(range(len(ROW_LABELS))) if rows is None else list(rows)

    tokens = _word_row(("Term", "x", "Tenor"), _HEADER_Y, left=_ANCHOR_LEFT)
    for column_index, label in enumerate(strike_labels):
        tokens.append(
            _token(label, right=_column_right(column_index), y_center=_HEADER_Y)
        )
    # Drawn at their position in *this* screenshot, not at their index in the
    # whole table: a screenshot of rows 40-70 starts at the top of its own
    # crop, and a screen that genuinely does not carry a row simply draws the
    # rows it does have one after another. Laying them out by table index
    # instead would leave a gap wherever a row was left out, which the pitch
    # check reads -- correctly -- as a row label the reader missed, and no
    # test of *coverage* could then be told apart from a test of geometry.
    for position, row_index in enumerate(row_indices):
        term, tenor = ROW_LABELS[row_index]
        if row_index not in omit_row_labels:
            tokens.extend(
                _word_row((term, "X", tenor), _row_y(position), left=_ANCHOR_LEFT)
            )
        for column_index in range(len(strike_labels)):
            if (row_index, column_index) in omit_cells:
                continue
            text = value_overrides.get(
                (row_index, column_index),
                f"{_synthetic_value(row_index, column_index):.2f}",
            )
            tokens.append(
                _token(text, right=_column_right(column_index), y_center=_row_y(position))
            )
    return tokens


def screenshot_tokens(*, chrome: dict | None = None, **kwargs) -> list[VCUBTextToken]:
    return chrome_tokens(**(chrome or {})) + matrix_tokens(**kwargs)


def provenance(reference: str = "otm.png", digest_seed: str = "a") -> VCUBCaptureProvenance:
    return VCUBCaptureProvenance(
        source_reference=reference,
        source_image_sha256=digest_seed * 64,
        source_image_bytes=2048,
        captured_at="2026-08-21T09:30:00Z",
        parser_name=PARSER_NAME,
        parser_version=PARSER_VERSION,
    )


def read(tokens: Sequence[VCUBTextToken], reference="otm.png", digest_seed="a"):
    return parse_vcub_otm_tokens(
        tokens, provenance=provenance(reference, digest_seed)
    )


def codes(issues) -> list[str]:
    return [issue.code for issue in issues]


