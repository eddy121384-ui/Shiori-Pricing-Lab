"""Structural tests for the VCUB ATM Swaptions template parser (Issue #181).

Every fixture here is **synthetic**: the labels are ordinary tenor buckets
and the numbers are generated by :func:`_synthetic_value` from row/column
indices. Nothing in this file is a Bloomberg screen capture, a Bloomberg
screen layout measurement, or a live market quote -- this repository is
public, so the real screenshot stays operator-local and is supplied by path
at live acceptance.

The token layer is where these tests bite, because that is the parser's own
contract: a reader hands it text with boxes, and everything Issue #181 cares
about (order, cell mapping, fail-closed behaviour, scale/crop independence)
is decided from those boxes alone. The small end-to-end image test lives in
``test_bloomberg_vcub_ocr.py``.
"""

from __future__ import annotations

import pytest

from shiori_pricing_lab.data.bloomberg_vcub_atm_template import (
    parse_vcub_atm_tokens,
)
from shiori_pricing_lab.data.bloomberg_vcub_capture import (
    METADATA_FIELDS,
    VCUBCaptureProvenance,
    VCUBCaptureStatus,
    VCUBTextToken,
)

# ---------------------------------------------------------------------------
# Synthetic fixture
# ---------------------------------------------------------------------------

EXPIRY_LABELS = ("1Mo", "2Mo", "3Mo", "6Mo", "9Mo", "1Yr", "18Mo", "2Yr")
TENOR_LABELS = ("1Yr", "2Yr", "3Yr", "4Yr", "5Yr", "6Yr")

_HEADER_Y = 110.0
_FIRST_ROW_Y = 140.0
_ROW_PITCH = 28.0
_FIRST_COLUMN_X = 160.0
_COLUMN_PITCH = 80.0
_ANCHOR_X = 40.0
_GLYPH_HEIGHT = 14.0


def _synthetic_value(row_index: int, column_index: int) -> float:
    """A made-up, strictly distinct number per intersection -- never a real quote."""

    return round(80.0 + row_index * 1.5 + column_index * 0.25, 2)


def _token(
    text: str, x_center: float, y_center: float, *, width: float | None = None
) -> VCUBTextToken:
    width = len(text) * 8.0 if width is None else width
    return VCUBTextToken(
        text=text,
        left=x_center - width / 2.0,
        top=y_center - _GLYPH_HEIGHT / 2.0,
        width=width,
        height=_GLYPH_HEIGHT,
        confidence=0.99,
    )


def _row_y(row_index: int) -> float:
    return _FIRST_ROW_Y + row_index * _ROW_PITCH


def _column_x(column_index: int) -> float:
    return _FIRST_COLUMN_X + column_index * _COLUMN_PITCH


def metadata_tokens() -> list[VCUBTextToken]:
    """The header context above the matrix, as separate word tokens."""

    tokens = [
        _token("USD", 60.0, 20.0),
        _token("RFR", 100.0, 20.0),
        _token("BVOL", 145.0, 20.0),
        _token("Cube", 195.0, 20.0),
        _token("(Default)", 260.0, 20.0),
        _token("ATM", 60.0, 50.0),
        _token("Swaptions", 130.0, 50.0),
        _token("Mid", 230.0, 50.0),
        _token("08/18/26", 300.0, 50.0),
        _token("Type", 60.0, 80.0),
        _token("Normal", 120.0, 80.0),
        _token("Vol", 165.0, 80.0),
        _token("(OIS)", 210.0, 80.0),
        _token("Source", 280.0, 80.0),
        _token("BVOL", 340.0, 80.0),
    ]
    return tokens


def grid_tokens(
    *,
    omit_cells: frozenset[tuple[int, int]] = frozenset(),
    value_overrides: dict[tuple[int, int], str] | None = None,
) -> list[VCUBTextToken]:
    """The matrix itself: the corner anchor, both axes, and every cell.

    Cell centres are nudged right of their header centres so the fixture
    never accidentally proves the mapping only for perfectly centred text.
    """

    value_overrides = value_overrides or {}
    tokens = [_token("Expiry", _ANCHOR_X + 22.0, _HEADER_Y, width=44.0)]
    for column_index, label in enumerate(TENOR_LABELS):
        tokens.append(_token(label, _column_x(column_index), _HEADER_Y))
    for row_index, label in enumerate(EXPIRY_LABELS):
        tokens.append(_token(label, _ANCHOR_X + 14.0, _row_y(row_index)))
    for row_index in range(len(EXPIRY_LABELS)):
        for column_index in range(len(TENOR_LABELS)):
            if (row_index, column_index) in omit_cells:
                continue
            text = value_overrides.get(
                (row_index, column_index),
                f"{_synthetic_value(row_index, column_index):.2f}",
            )
            tokens.append(
                _token(text, _column_x(column_index) + 6.0, _row_y(row_index))
            )
    return tokens


def outside_grid_tokens() -> list[VCUBTextToken]:
    """Chrome that must never become a cell: a footer and a right-hand caption."""

    return [
        _token("Zoom", 120.0, 400.0),
        _token("100%", 175.0, 400.0),
        _token("Scroll", 720.0, _row_y(2)),
    ]


def canonical_tokens(**kwargs) -> list[VCUBTextToken]:
    return metadata_tokens() + grid_tokens(**kwargs) + outside_grid_tokens()


def provenance(**overrides) -> VCUBCaptureProvenance:
    fields = {
        "source_reference": "vcub_atm_usd.png",
        "source_image_sha256": "a" * 64,
        "source_image_bytes": 4096,
        "captured_at": "2026-08-18T09:30:00Z",
    }
    fields.update(overrides)
    return VCUBCaptureProvenance(**fields)


def parse(tokens) -> object:
    return parse_vcub_atm_tokens(tokens, provenance=provenance())


def transform(tokens, *, scale: float = 1.0, dx: float = 0.0, dy: float = 0.0):
    """Re-render the same screen at another zoom/crop, as a real recapture would."""

    return [
        VCUBTextToken(
            text=token.text,
            left=token.left * scale + dx,
            top=token.top * scale + dy,
            width=token.width * scale,
            height=token.height * scale,
            confidence=token.confidence,
        )
        for token in tokens
    ]


def codes(issues) -> list[str]:
    return [issue.code for issue in issues]


