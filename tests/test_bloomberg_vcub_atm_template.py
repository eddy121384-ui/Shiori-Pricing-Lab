@pytest.mark.parametrize("scale", [0.8, 1.25, 1.5, 2.0])
def test_a_rescaled_capture_maps_every_cell_identically(scale: float) -> None:
    baseline = parse(canonical_tokens()).grid.to_dict()

    rescaled = parse(transform(canonical_tokens(), scale=scale)).grid.to_dict()

    assert rescaled == baseline


@pytest.mark.parametrize("dx,dy", [(-37.0, -52.0), (410.0, 260.0), (-19.5, 8.25)])
def test_a_recropped_or_repositioned_capture_maps_every_cell_identically(
    dx: float, dy: float
) -> None:
    baseline = parse(canonical_tokens()).grid.to_dict()

    moved = parse(transform(canonical_tokens(), dx=dx, dy=dy)).grid.to_dict()

    assert moved == baseline


def test_a_rescaled_and_recropped_capture_still_has_no_blocking_errors() -> None:
    capture = parse(transform(canonical_tokens(), scale=1.75, dx=-140.0, dy=-95.0))

    assert codes(capture.blocking_errors) == []
    assert capture.grid.value_at("3Mo", "4Yr") == pytest.approx(_synthetic_value(2, 3))


def test_small_per_token_jitter_does_not_move_a_value_into_a_neighbouring_cell() -> None:
    """Sub-pixel-ish detection wobble is normal and must not change any mapping."""

    tokens = canonical_tokens()
    jittered = [
        VCUBTextToken(
            text=token.text,
            left=token.left + (index % 5 - 2) * 0.9,
            top=token.top + (index % 3 - 1) * 0.7,
            width=token.width,
            height=token.height,
            confidence=token.confidence,
        )
        for index, token in enumerate(tokens)
    ]

    assert parse(jittered).grid.to_dict() == parse(tokens).grid.to_dict()


