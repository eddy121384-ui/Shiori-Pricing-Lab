def test_a_malformed_numeric_cell_is_surfaced_and_left_unresolved() -> None:
    capture = parse(canonical_tokens(value_overrides={(2, 3): "8S.15"}))

    blocking = [
        issue for issue in capture.blocking_errors if issue.code == "MALFORMED_NUMERIC_CELL"
    ]
    assert [(issue.expiry, issue.tenor) for issue in blocking] == [("3Mo", "4Yr")]
    assert capture.grid.value_at("3Mo", "4Yr") is None
    assert not capture.can_confirm


@pytest.mark.parametrize("text", ["NaN", "Infinity", "-inf", "1e999"])
def test_a_non_finite_or_exponent_cell_never_becomes_a_value(text: str) -> None:
    capture = parse(canonical_tokens(value_overrides={(1, 1): text}))

    assert codes(capture.blocking_errors) != []
    assert capture.grid.value_at("2Mo", "2Yr") is None
    assert not capture.can_confirm


def test_a_thousands_separated_number_still_reads_as_one_value() -> None:
    capture = parse(canonical_tokens(value_overrides={(0, 0): "1,234.50"}))

    assert capture.grid.value_at("1Mo", "1Yr") == pytest.approx(1234.50)
    assert codes(capture.blocking_errors) == []


