def test_metadata_reads_the_screen_header_verbatim() -> None:
    metadata = parse(canonical_tokens()).metadata

    assert metadata.currency == "USD"
    assert metadata.curve_config == "USD RFR BVOL Cube (Default)"
    assert metadata.side == "Mid"
    assert metadata.quote_date == "08/18/26"
    assert metadata.tab == "ATM Swaptions"
    assert metadata.vol_type == "Normal Vol (OIS)"
    assert metadata.source == "BVOL"
    assert metadata.unresolved_fields == ()


def test_metadata_that_cannot_be_read_is_marked_unresolved_and_not_invented() -> None:
    tokens = [
        token
        for token in canonical_tokens()
        if token.text not in {"Mid", "08/18/26", "Cube", "(Default)"}
    ]

    metadata = parse(tokens).metadata

    assert metadata.side is None
    assert metadata.quote_date is None
    assert metadata.curve_config is None
    assert set(metadata.unresolved_fields) == {"side", "quote_date", "curve_config"}


def test_two_candidate_dates_leave_the_date_unresolved_rather_than_guessing() -> None:
    tokens = canonical_tokens()
    tokens.append(_token("08/19/26", 400.0, 50.0))

    metadata = parse(tokens).metadata

    assert metadata.quote_date is None
    assert "quote_date" in metadata.unresolved_fields


def test_metadata_survives_a_grid_that_failed_closed() -> None:
    tokens = [token for token in canonical_tokens() if token.text != "Expiry"]

    capture = parse(tokens)

    assert capture.grid is None
    assert capture.metadata.currency == "USD"
    assert capture.metadata.vol_type == "Normal Vol (OIS)"


def test_every_unresolved_metadata_field_is_a_known_field_name() -> None:
    capture = parse([_token("nothing", 10.0, 10.0)])

    assert set(capture.metadata.unresolved_fields) <= set(METADATA_FIELDS)
    assert capture.grid is None


def test_the_vol_type_is_carried_verbatim_and_never_relabelled() -> None:
    """Normal/yield vol must never be silently renamed to a price vol."""

    metadata = parse(canonical_tokens()).metadata

    assert metadata.vol_type == "Normal Vol (OIS)"
    assert "PRICE_VOL" not in str(metadata.to_dict())
