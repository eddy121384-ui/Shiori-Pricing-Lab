def test_canonical_synthetic_atm_grid_parses_with_no_blocking_errors() -> None:
    capture = parse(canonical_tokens())

    assert codes(capture.blocking_errors) == []
    assert capture.grid is not None
    assert capture.review_status is VCUBCaptureStatus.PENDING_REVIEW


def test_expiry_labels_keep_the_screen_order_down_the_rows() -> None:
    capture = parse(canonical_tokens())

    assert capture.grid.expiry_labels == EXPIRY_LABELS


def test_tenor_labels_keep_the_screen_order_across_the_columns() -> None:
    capture = parse(canonical_tokens())

    assert capture.grid.tenor_labels == TENOR_LABELS


def test_every_value_lands_on_its_own_expiry_and_tenor_intersection() -> None:
    capture = parse(canonical_tokens())

    for row_index, expiry in enumerate(EXPIRY_LABELS):
        for column_index, tenor in enumerate(TENOR_LABELS):
            assert capture.grid.value_at(expiry, tenor) == pytest.approx(
                _synthetic_value(row_index, column_index)
            ), f"{expiry} x {tenor} is not the value drawn at that intersection"


def test_a_shuffled_token_order_changes_nothing_because_placement_is_geometric() -> None:
    tokens = canonical_tokens()
    shuffled = list(reversed(tokens))

    assert parse(shuffled).grid.to_dict() == parse(tokens).grid.to_dict()


